/// Режим следования карты за индикатором пользователя.
///
/// Повторяет `MapMode` нативного SDK.
enum VkMapMode {
  /// Камера не привязана к индикатору пользователя.
  free,

  /// Центр карты закреплён на индикаторе пользователя.
  followLocation,

  /// Центр карты закреплён на индикаторе, а поворот следует его направлению.
  followBearingAndLocation,
}
